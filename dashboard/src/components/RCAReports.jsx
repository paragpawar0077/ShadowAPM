import React, { useEffect, useState } from "react";
import { api } from "../api.js";

export default function RCAReports() {
  const [reports, setReports] = useState([]);
  const [requestId, setRequestId] = useState("");
  const [error, setError] = useState(null);
  const [expanded, setExpanded] = useState(null);
  const [busy, setBusy] = useState(false);

  const refresh = async () => {
    try {
      setError(null);
      setReports(await api.listRCA());
    } catch (e) {
      setError(e.message);
    }
  };

  useEffect(() => {
    refresh();
    const id = setInterval(refresh, 8000);
    return () => clearInterval(id);
  }, []);

  const generate = async () => {
    if (!requestId.trim()) return;
    setBusy(true);
    try {
      await api.generateRCA(requestId.trim());
      setRequestId("");
      refresh();
    } catch (e) {
      setError(e.message);
    } finally {
      setBusy(false);
    }
  };

  return (
    <>
      {error && <div className="panel" style={{ borderColor: "#f87171" }}>⚠ {error} — is rca-agent running?</div>}

      <div className="panel">
        <h2>Generate a root-cause report</h2>
        <div className="form-row">
          <input
            placeholder="request_id (from telemetry / an anomalous request)"
            style={{ width: 340 }}
            value={requestId}
            onChange={(e) => setRequestId(e.target.value)}
          />
          <button onClick={generate} disabled={busy}>{busy ? "Generating…" : "Run RCA"}</button>
        </div>
        <p className="muted" style={{ fontSize: 12 }}>
          Uses a locally hosted Ollama model when available, evidence-linked to the raw telemetry — with
          a deterministic rule-based explanation as a zero-cost fallback if Ollama isn't reachable.
        </p>
      </div>

      <div className="panel">
        <h2>All RCA reports</h2>
        <table>
          <thead>
            <tr><th>Request</th><th>Root cause</th><th>Confidence</th><th>Generated by</th><th></th></tr>
          </thead>
          <tbody>
            {reports.map((r) => (
              <React.Fragment key={r.id}>
                <tr>
                  <td className="mono">{r.request_id?.slice(0, 10)}…</td>
                  <td>{r.root_cause}</td>
                  <td>
                    <span className={`badge ${r.confidence === "high" ? "danger" : r.confidence === "medium" ? "warn" : "muted"}`}>
                      {r.confidence}
                    </span>
                  </td>
                  <td className="muted">{r.generated_by}</td>
                  <td>
                    <button className="secondary" onClick={() => setExpanded(expanded === r.id ? null : r.id)}>
                      {expanded === r.id ? "Hide evidence" : "View evidence"}
                    </button>
                  </td>
                </tr>
                {expanded === r.id && (
                  <tr>
                    <td colSpan={5}>
                      <div className="evidence-block">{JSON.stringify(r, null, 2)}</div>
                    </td>
                  </tr>
                )}
              </React.Fragment>
            ))}
            {reports.length === 0 && (
              <tr><td colSpan={5} className="muted">No RCA reports yet.</td></tr>
            )}
          </tbody>
        </table>
      </div>
    </>
  );
}
